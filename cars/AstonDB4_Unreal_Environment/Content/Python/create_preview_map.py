"""Optional: create a saved editor-visible Coastal Pass map after compiling the C++ project.
Run inside Unreal Editor: Tools > Execute Python Script > create_preview_map.py
Then select File > Save All and Play; GameMode adds lighting and player.
"""
import unreal

NAME='/Game/DB4/Maps/CoastalPass'
sub=unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
assets=unreal.EditorAssetLibrary
if assets.does_asset_exist(NAME):
    success=sub.load_level(NAME)
else:
    success=sub.new_level(NAME,False)
if not success:raise RuntimeError('Could not open or create '+NAME)
actor_class=getattr(unreal,'DB4Environment',None)
if actor_class is None:
    raise RuntimeError('C++ module AstonDB4 is not compiled/loaded. Build the project and restart editor.')
actors=unreal.EditorLevelLibrary.get_all_level_actors()
if not any(a.get_class().get_name()=='DB4Environment' for a in actors):
    actor=unreal.EditorLevelLibrary.spawn_actor_from_class(actor_class,unreal.Vector(0,0,0))
    actor.set_actor_label('DB4 · Coastal Pass | Procedural Environment')
    unreal.log('DB4 environment generated in editor. Select actor > Details > Photorealism | Fab Overrides to assign real scanned trees/rocks/shrubs.')
# Preview is the editable authored landscape; the player and atmospheric lights are generated by game mode during Play.
unreal.EditorLevelLibrary.set_level_viewport_camera_info(unreal.Vector(1800,-3600,1450),unreal.Rotator(-13,20,0))
sub.save_current_level()
unreal.log('DB4 READY: Map '+NAME+' saved. Hit Play to enter the vehicle.')
